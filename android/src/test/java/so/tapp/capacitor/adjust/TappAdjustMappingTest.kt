    @Test
    fun failuresContainOnlyErrorAndMessage() {
        assertEquals(mapOf("error" to true, "message" to "backend failure"),
            TappAdjustMapping.linkData(response().copy(error = true, message = "backend failure", tappUrl = "ignored")))
        assertEquals(mapOf("error" to true, "message" to "No link data returned"), TappAdjustMapping.linkData(null))
        assertEquals(mapOf("error" to true, "message" to "An unexpected error occurred"),
            TappAdjustMapping.linkData(response().copy(error = true, message = null)))
        assertEquals(mapOf("error" to true, "message" to "Tapp has not been started. Call start() first."),
            TappAdjustMapping.error(TappAdjustMapping.NOT_STARTED))
    }

