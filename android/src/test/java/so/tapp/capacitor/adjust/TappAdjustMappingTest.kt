    @Test
    fun playStoreSubscriptionValidatesAndConvertsToLong() {
        val valid = TappAdjustMapping.playStoreSubscription(199.9, "EUR", "sku", "order", "sig", "token", 1700000000000.0)
        assertEquals(TappAdjustMapping.PlayStoreSubscription(199L, "EUR", "sku", "order", "sig", "token", 1700000000000L), valid)
        assertEquals(500L, TappAdjustMapping.playStoreSubscription(500, "EUR", "s", "o", "g", "t", null)!!.price)
        assertNull(TappAdjustMapping.playStoreSubscription(1, "EUR", "s", "o", "g", "t", JSONObject.NULL)!!.purchaseTime)
        listOf(Double.NaN, Double.POSITIVE_INFINITY, "1", true, null, JSONObject.NULL).forEach {
            assertNull("price $it", TappAdjustMapping.playStoreSubscription(it, "EUR", "s", "o", "g", "t", null))
        }
        listOf(Double.NaN, Double.NEGATIVE_INFINITY, "1", false).forEach {
            assertNull("purchaseTime $it", TappAdjustMapping.playStoreSubscription(1, "EUR", "s", "o", "g", "t", it))
        }
        for (blank in 1..5) {
            val strings = MutableList<Any?>(5) { "x" }
            strings[blank - 1] = " "
            assertNull(TappAdjustMapping.playStoreSubscription(1, strings[0], strings[1], strings[2], strings[3], strings[4], null))
            strings[blank - 1] = null
            assertNull(TappAdjustMapping.playStoreSubscription(1, strings[0], strings[1], strings[2], strings[3], strings[4], null))
        }
    }

    @Test
    fun adRevenueRejectsBlankAndNonFiniteOrNegativeValues() {
        assertEquals(TappAdjustMapping.AdRevenue("admob", 0.0, "EUR"), TappAdjustMapping.adRevenue("admob", 0, "EUR"))
        assertEquals(TappAdjustMapping.AdRevenue("admob", 1.25, "USD"), TappAdjustMapping.adRevenue("admob", 1.25, "USD"))
        listOf(-0.01, Double.NaN, Double.POSITIVE_INFINITY, "1", true, null).forEach {
            assertNull("revenue $it", TappAdjustMapping.adRevenue("admob", it, "EUR"))
        }
        assertNull(TappAdjustMapping.adRevenue(" ", 1, "EUR"))
        assertNull(TappAdjustMapping.adRevenue("admob", 1, ""))
    }

    @Test
    fun primitiveValidationIsStrict() {
        assertEquals("a", TappAdjustMapping.nonBlank("a"))
        listOf(null, JSONObject.NULL, "", " \t", 1, true).forEach { assertNull(TappAdjustMapping.nonBlank(it)) }
        assertEquals(true, TappAdjustMapping.bool(true))
        assertEquals(false, TappAdjustMapping.bool(false))
        listOf(null, JSONObject.NULL, "true", 1, 0).forEach { assertNull(TappAdjustMapping.bool(it)) }
        assertEquals(3.0, TappAdjustMapping.finite(3)!!, 0.0)
        listOf(null, Double.NaN, Float.POSITIVE_INFINITY, "3", true).forEach { assertNull(TappAdjustMapping.finite(it)) }
    }

    @Test
    fun lifecycleForwardsOnlyAfterStart() {
        assertFalse(TappAdjustMapping.shouldForwardLifecycle(started = false))
        assertTrue(TappAdjustMapping.shouldForwardLifecycle(started = true))
    }

    @Test
    fun initialResumeIsForwardedOnceOnlyWhenAlreadyResumed() {
        assertTrue(TappAdjustMapping.shouldForwardInitialResume(started = true, activityResumed = true, resumeForwarded = false))
        // handleOnResume already forwarded this resume: no double call.
        assertFalse(TappAdjustMapping.shouldForwardInitialResume(started = true, activityResumed = true, resumeForwarded = true))
        // Not resumed yet: the coming handleOnResume forwards it.
        assertFalse(TappAdjustMapping.shouldForwardInitialResume(started = true, activityResumed = false, resumeForwarded = false))
        assertFalse(TappAdjustMapping.shouldForwardInitialResume(started = false, activityResumed = true, resumeForwarded = false))
    }

    @Test
    fun onceSettlesOnlyOnce() {
        val once = TappAdjustMapping.Once()
        assertTrue(once.claim())
        assertFalse(once.claim())
        assertFalse(once.claim())
    }
