class TappAdjustMappingTest {
    @Test
    fun mapsEveryStandardEventInContractOrder() {
        val names = listOf(
            "add_payment_info", "add_to_cart", "add_to_wishlist", "complete_registration",
            "contact", "customize_product", "donate", "find_location", "initiate_checkout",
            "generate_lead", "purchase", "schedule", "search", "start_trial", "submit_application",
            "subscribe", "view_content", "click_button", "download_file", "join_group",
            "achieve_level", "create_group", "create_role", "link_click", "link_impression",
            "apply_for_loan", "loan_approval", "loan_disbursal", "login", "rate", "spend_credits",
            "unlock_achievement", "add_shipping_info", "earn_virtual_currency", "start_level",
            "complete_level", "post_score", "select_content", "begin_tutorial", "complete_tutorial"
        )
        names.forEachIndexed { index, name ->
            val action = TappAdjustMapping.eventAction(index + 1)!!
            assertEquals(index + 1, action.rawValue)
            assertEquals("tapp_$name", action.javaClass.simpleName)
            assertFalse(action.isCustom)
            assertEquals(action, TappAdjustMapping.eventAction((index + 1).toDouble()))
        }
    }

    @Test
    fun customEventsUseProvidedNameOrDefault() {
        assertEquals(RequestModels.EventAction.custom("checkout"), TappAdjustMapping.eventAction(0, "checkout"))
        listOf(null, "", "   ").forEach { customValue ->
            assertEquals(
                RequestModels.EventAction.custom("custom_event_autogenerated"),
                TappAdjustMapping.eventAction(0, customValue)
            )
        }
        assertEquals(RequestModels.EventAction.custom(" checkout "), TappAdjustMapping.eventAction(0, " checkout "))
    }

    @Test
    fun rejectsMalformedAndDisallowedUrls() {
        listOf(
            null, "", "   ", " \n\t", "no-scheme/path",
            "https://[invalid", "http://exa mple.com",
            "javascript:alert(1)", "JavaScript:alert(1)",
            "data:text/plain,x", "DATA:text/plain,x",
            "file:///etc/hosts", "FILE:///etc/hosts"
        ).forEach {
            assertNull("Unexpected valid URL: $it", TappAdjustMapping.parsedUrl(it))
