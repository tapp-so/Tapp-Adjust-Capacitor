    }

    @Test
    fun returnsTrimmedUrls() {
        listOf(
            "https://example.com/path" to "https://example.com/path",
            "http://example.com" to "http://example.com",
            "myapp://x" to "myapp://x",
            "  https://example.com/a  " to "https://example.com/a"
        ).forEach { (value, expected) ->
            assertEquals(expected, TappAdjustMapping.parsedUrl(value))
        }
    }

    @Test
    fun rejectsInvalidActionsWithoutCoercingOrTruncating() {
        listOf(null, JSONObject.NULL, "1", true, -1, 41, 1.5, Double.NaN,
            Double.POSITIVE_INFINITY, Double.NEGATIVE_INFINITY, Long.MAX_VALUE).forEach {
            assertNull("Unexpected action for $it", TappAdjustMapping.eventAction(it))
        }
    }

    @Test
    fun metadataKeepsOnlyFlatJsonScalars() {
        val input = linkedMapOf(
            "text" to "value", "empty" to "", "flag" to false, "int" to 3,
            "long" to 4L, "double" to 2.5, "zero" to 0,
            "null" to null, "jsonNull" to JSONObject.NULL, "object" to JSONObject(),
            "map" to mapOf("key" to "value"), "list" to listOf(1),
            "nan" to Double.NaN, "infinity" to Double.POSITIVE_INFINITY,
            "negativeInfinity" to Float.NEGATIVE_INFINITY
        )
        val expected = mapOf("text" to "value", "empty" to "", "flag" to false,
            "int" to 3, "long" to 4L, "double" to 2.5, "zero" to 0)
        assertEquals(expected, TappAdjustMapping.metadata(input))
        assertEquals(expected.keys, JSONObject(TappAdjustMapping.metadata(input)!!).keys().asSequence().toSet())
        assertTrue(input.containsKey("nan"))
        assertNull(TappAdjustMapping.metadata(null))
        assertEquals(emptyMap<String, Any>(), TappAdjustMapping.metadata(emptyMap<String, Any>()))
    }

    @Test
