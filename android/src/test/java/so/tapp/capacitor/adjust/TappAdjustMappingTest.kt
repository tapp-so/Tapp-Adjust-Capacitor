        listOf("adid", "costInUsd", "callbackParams", "partnerParams").forEach { assertFalse(full.containsKey(it)) }
    }

    @Test
    fun installReferrerIsTypedSubsetOmittingUnavailableValues() {
        assertEquals(mapOf(
            "installReferrer" to "utm_source=x", "referrerClickTimestampSeconds" to 10L,
            "installBeginTimestampSeconds" to 20L
        ), TappAdjustMapping.installReferrer("utm_source=x", 10L, 20L))
