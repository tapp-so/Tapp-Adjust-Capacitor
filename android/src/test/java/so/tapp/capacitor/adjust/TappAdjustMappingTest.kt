    private val coreMethods = setOf(
        "start", "url", "handleTappEvent", "shouldProcess", "fetchLinkData", "fetchOriginLinkData"
    )

    private val expectedIosOnly = setOf(
        "adjustVerifyAppStorePurchase", "adjustTrackAppStoreSubscription", "adjustConvert",
        "adjustRequestAppTrackingAuthorization", "adjustAppTrackingAuthorizationStatus",
        "adjustUpdateSkanConversionValue"
    )

    /** Method names declared in the TappAdjustPlugin interface of src/definitions.ts. */
    private fun definitionsAdjustMethods(): Set<String> {
        val source = File("../src/definitions.ts").readText()
        val start = source.indexOf("export interface TappAdjustPlugin extends TappPlugin {")
        assertTrue("TappAdjustPlugin interface not found", start >= 0)
        val body = source.substring(start, source.indexOf("\n}", start))
        return Regex("""^  (\w+)\(""", RegexOption.MULTILINE).findAll(body).map { it.groupValues[1] }.toSet()
    }

    private val allAdjustMethods = TappAdjustMapping.SHARED_METHODS + TappAdjustMapping.ANDROID_ONLY_METHODS +
        TappAdjustMapping.IOS_ONLY_METHODS

    @Test
    fun methodListsMatchTypeScriptApiExactly() {
        val declared = definitionsAdjustMethods()
        assertEquals(34, declared.size)
        assertEquals(declared, allAdjustMethods)
        assertTrue((TappAdjustMapping.SHARED_METHODS intersect TappAdjustMapping.ANDROID_ONLY_METHODS).isEmpty())
        assertTrue((TappAdjustMapping.SHARED_METHODS intersect TappAdjustMapping.IOS_ONLY_METHODS).isEmpty())
        assertTrue((TappAdjustMapping.ANDROID_ONLY_METHODS intersect TappAdjustMapping.IOS_ONLY_METHODS).isEmpty())
    }

    @Test
    fun pluginExposesExactlyCoreAndAdjustMethods() {
        val pluginMethods = TappAdjustPlugin::class.java.declaredMethods
            .filter { it.isAnnotationPresent(PluginMethod::class.java) }
            .map { it.name }.toSet()
        assertEquals(coreMethods + definitionsAdjustMethods(), pluginMethods)
        listOf("adjustOnResume", "adjustOnPause", "getConfig", "handleOnNewIntent").forEach { name ->
            assertFalse(name, TappAdjustPlugin::class.java.declaredMethods.any { it.name == name })
        }
    }

    @Test
    fun androidPlatformGateIsExactlyTheIosOnlyList() {
        assertEquals(expectedIosOnly, TappAdjustMapping.IOS_ONLY_METHODS)
        val gated = allAdjustMethods.filter {
            TappAdjustMapping.gate(it, started = true) == TappAdjustMapping.Gate.UNIMPLEMENTED
        }.toSet()
        assertEquals(expectedIosOnly, gated)
        expectedIosOnly.forEach {
            // Platform gate comes before the start check.
            assertEquals(TappAdjustMapping.Gate.UNIMPLEMENTED, TappAdjustMapping.gate(it, started = false))
        }
        assertEquals("adjustConvert is not available on Android.", TappAdjustMapping.unimplementedMessage("adjustConvert"))
    }

    @Test
    fun notStartedGateCoversEveryAdjustMethodAndHandleEvent() {
        val available = TappAdjustMapping.SHARED_METHODS + TappAdjustMapping.ANDROID_ONLY_METHODS
        assertTrue("handleEvent" in available)
        assertTrue(definitionsAdjustMethods().filter { it.startsWith("adjust") }.all { it in allAdjustMethods })
        available.forEach {
            assertEquals(it, TappAdjustMapping.Gate.NOT_STARTED, TappAdjustMapping.gate(it, started = false))
            assertEquals(it, TappAdjustMapping.Gate.PROCEED, TappAdjustMapping.gate(it, started = true))
        }
    }

