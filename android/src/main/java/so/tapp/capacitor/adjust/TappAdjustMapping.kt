    fun parsedUrl(value: String?): String? {
        val trimmed = value?.trim()?.takeIf { it.isNotEmpty() } ?: return null
        return try {
            val uri = URI(trimmed)
            val scheme = uri.scheme
            if (!uri.isAbsolute || scheme.isNullOrEmpty() ||
                listOf("javascript", "data", "file").any { it.equals(scheme, ignoreCase = true) }
            ) return null
            trimmed
        } catch (_: URISyntaxException) {
            null
        }
    }

    fun metadata(values: Map<String, *>?): Map<String, Any>? = values?.let {
        val result = linkedMapOf<String, Any>()
        it.forEach { (key, value) ->
            when (value) {
                is String, is Boolean -> result[key] = value
                is Number -> if (value.toDouble().isFinite()) result[key] = value
            }
        }
        result
    }

    fun stringData(values: Map<String, *>?): Map<String, String> = buildMap {
        values?.forEach { (key, value) -> if (value is String) put(key, value) }
    }

    private val sentinels = setOf(
        "tapp_url was not returned", "attr_tapp_url was not returned",
        "influencer was not returned", "deepLink was not returned"
    )

    fun optionalString(value: String?): String? {
        val trimmed = value?.trim() ?: return null
        return value.takeUnless {
            trimmed.isEmpty() || trimmed.equals("null", ignoreCase = true) ||
                trimmed == "-1" || trimmed in sentinels
        }
    }

    fun error(message: String?): Map<String, Any> = mapOf(
        "error" to true,
        "message" to (optionalString(message) ?: "An unexpected error occurred")
    )

    fun linkData(response: RequestModels.TappLinkDataResponse?): Map<String, Any> {
        if (response == null) return error("No link data returned")
        if (response.error) return error(response.message)
        return linkedMapOf<String, Any>("error" to false).apply {
            optionalString(response.tappUrl)?.let { put("tappUrl", it) }
            optionalString(response.attrTappUrl)?.let { put("attrTappUrl", it) }
            optionalString(response.influencer)?.let { put("influencer", it) }
            response.data?.let { put("data", stringData(it)) }
            response.isFirstSession?.let { put("isFirstSession", it) }
            optionalString(response.deepLink)?.let { put("deepLink", it) }
        }
    }

    // --- Adjust adapter ---

    const val ADJUST_FAILED = "The Adjust SDK call failed."

    /** Methods that exist only on iOS; Android rejects them with UNIMPLEMENTED before any other check. */
    val IOS_ONLY_METHODS: Set<String> = setOf(
        "adjustVerifyAppStorePurchase", "adjustTrackAppStoreSubscription", "adjustConvert",
        "adjustRequestAppTrackingAuthorization", "adjustAppTrackingAuthorizationStatus",
        "adjustUpdateSkanConversionValue"
    )

    /** Adjust methods available on both platforms. */
    val SHARED_METHODS: Set<String> = setOf(
        "handleEvent", "getAdjustAttribution", "adjustGetAdid", "adjustGetIdfa", "adjustTrackAdRevenue",
        "adjustSetPushToken", "adjustGdprForgetMe", "adjustTrackThirdPartySharing",
        "adjustTrackMeasurementConsent", "adjustEnable", "adjustDisable", "adjustIsEnabled",
        "adjustSwitchToOfflineMode", "adjustSwitchBackToOnlineMode",
        "adjustAddGlobalCallbackParameter", "adjustAddGlobalPartnerParameter",
        "adjustRemoveGlobalCallbackParameter", "adjustRemoveGlobalPartnerParameter",
        "adjustRemoveGlobalCallbackParameters", "adjustRemoveGlobalPartnerParameters", "adjustGetSdkVersion"
    )

    /** Adjust methods available only on Android. */
    val ANDROID_ONLY_METHODS: Set<String> = setOf(
        "adjustTrackPlayStoreSubscription", "adjustVerifyPlayStorePurchase",
        "adjustVerifyAndTrackPlayStorePurchase", "adjustGetGoogleAdId", "adjustGetAmazonAdId",
        "adjustGetGooglePlayInstallReferrer", "adjustSetReferrer"
    )

    enum class Gate { UNIMPLEMENTED, NOT_STARTED, PROCEED }

    /** Gate order for every Adjust method: platform first, then start state. Input validation follows. */
    fun gate(method: String, started: Boolean): Gate = when {
        method in IOS_ONLY_METHODS -> Gate.UNIMPLEMENTED
        !started -> Gate.NOT_STARTED
        else -> Gate.PROCEED
    }

    fun unimplementedMessage(method: String) = "$method is not available on Android."

    // --- Input validation (raw JSON values from PluginCall.data) ---

    fun nonBlank(value: Any?): String? = (value as? String)?.takeUnless { it.isBlank() }

    fun finite(value: Any?): Double? = (value as? Number)?.toDouble()?.takeIf { it.isFinite() }

    fun bool(value: Any?): Boolean? = value as? Boolean

    data class AdRevenue(val source: String, val revenue: Double, val currency: String)

    /** The native SDK silently skips blank strings and non-finite or negative revenue, so reject them here. */
    fun adRevenue(source: Any?, revenue: Any?, currency: Any?): AdRevenue? {
        val s = nonBlank(source) ?: return null
        val r = finite(revenue)?.takeIf { it >= 0.0 } ?: return null
        val c = nonBlank(currency) ?: return null
        return AdRevenue(s, r, c)
    }

    data class PlayStoreSubscription(
        val price: Long, val currency: String, val sku: String, val orderId: String,
        val signature: String, val purchaseToken: String, val purchaseTime: Long?
    )

    /** price and the optional purchaseTime must be finite numbers; the native SDK takes Long. */
    fun playStoreSubscription(
        price: Any?, currency: Any?, sku: Any?, orderId: Any?, signature: Any?,
        purchaseToken: Any?, purchaseTime: Any?
    ): PlayStoreSubscription? {
        val p = finite(price) ?: return null
        val time = if (purchaseTime == null || purchaseTime == JSONObject.NULL) {
            null
        } else {
            finite(purchaseTime) ?: return null
        }
        return PlayStoreSubscription(
            p.toLong(), nonBlank(currency) ?: return null, nonBlank(sku) ?: return null,
            nonBlank(orderId) ?: return null, nonBlank(signature) ?: return null,
            nonBlank(purchaseToken) ?: return null, time?.toLong()
        )
    }

    // --- Native argument order ---

    data class NativeArgs(val first: String, val second: String)

    /** Android native is adjustAdd*Parameter(key, value): KEY first (iOS is value first). */
    fun globalParameterArgs(key: String, value: String) = NativeArgs(first = key, second = value)

    /**
     * AdjustPlayStorePurchase's constructor is (productId, purchaseToken) (verified with javap on
     * adjust-android 5.0.0). JS transactionId is the Play purchase token, so it goes SECOND.
     * Tapp-Adjust-RN passes these swapped; do not copy that.
     */
    fun playStorePurchaseArgs(transactionId: String, productId: String) =
        NativeArgs(first = productId, second = transactionId)

    // --- Results ---

    /** Maps Adjust attribution fields, omitting nulls (no placeholders). Null attribution maps to an empty object. */
    fun attribution(
        trackerToken: String? = null, trackerName: String? = null, network: String? = null,
        campaign: String? = null, adgroup: String? = null, creative: String? = null,
        clickLabel: String? = null, costType: String? = null, costAmount: Double? = null,
        costCurrency: String? = null, fbInstallReferrer: String? = null
    ): Map<String, Any> = linkedMapOf<String, Any>().apply {
        trackerToken?.let { put("trackerToken", it) }
        trackerName?.let { put("trackerName", it) }
        network?.let { put("network", it) }
        campaign?.let { put("campaign", it) }
        adgroup?.let { put("adgroup", it) }
        creative?.let { put("creative", it) }
        clickLabel?.let { put("clickLabel", it) }
        costType?.let { put("costType", it) }
        costAmount?.takeIf { it.isFinite() }?.let { put("costAmount", it) }
        costCurrency?.let { put("costCurrency", it) }
        fbInstallReferrer?.let { put("fbInstallReferrer", it) }
    }

    /** A single optional identifier result; the field is omitted when null or blank. */
    fun optionalField(key: String, value: String?): Map<String, Any> =
        if (value.isNullOrBlank()) emptyMap() else mapOf(key to value)

    /** Returns null when the native result lacks a required field, which the plugin rejects as UNAVAILABLE. */
    fun verifyResult(verificationStatus: String?, code: Int, message: String?): Map<String, Any>? {
        if (verificationStatus == null || message == null) return null
        return linkedMapOf("verificationStatus" to verificationStatus, "code" to code, "message" to message)
    }

    /**
     * Typed install referrer subset only. installReferrer is omitted when null or blank; a timestamp is
     * omitted when 0 or less (0 is the Play default for an unavailable value). Other native fields
     * (server timestamps, install version, instant flag) are never exposed.
     */
    fun installReferrer(installReferrer: String?, referrerClickTimestampSeconds: Long, installBeginTimestampSeconds: Long):
        Map<String, Any> = linkedMapOf<String, Any>().apply {
        if (!installReferrer.isNullOrBlank()) put("installReferrer", installReferrer)
        if (referrerClickTimestampSeconds > 0) put("referrerClickTimestampSeconds", referrerClickTimestampSeconds)
        if (installBeginTimestampSeconds > 0) put("installBeginTimestampSeconds", installBeginTimestampSeconds)
    }

    // --- Lifecycle ---

    /** handleOnResume/handleOnPause forward to the Adjust SDK only after a successful start(). */
    fun shouldForwardLifecycle(started: Boolean): Boolean = started

    /**
     * After the first successful start(), forward one resume if the Activity is already resumed and
     * handleOnResume has not already forwarded this resume. Evaluated on the main thread.
     */
    fun shouldForwardInitialResume(started: Boolean, activityResumed: Boolean, resumeForwarded: Boolean): Boolean =
        started && activityResumed && !resumeForwarded

    /** Lets a native callback settle a call at most once, whatever thread it arrives on. */
    class Once {
        private val claimed = AtomicBoolean(false)
        fun claim(): Boolean = claimed.compareAndSet(false, true)
    }
}
