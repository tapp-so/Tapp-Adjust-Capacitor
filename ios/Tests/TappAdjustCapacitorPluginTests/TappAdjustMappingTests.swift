    func testIOSPlatformGateListIsExactlyTheAndroidOnlyMethods() {
        XCTAssertEqual(Set(TappAdjustMapping.androidOnlyMethods.map(\.rawValue)), androidOnlyNames)
        for method in TappAdjustMapping.Method.allCases {
            let gatedBeforeStart = TappAdjustMapping.gateRejection(for: method, started: false)
            let gatedAfterStart = TappAdjustMapping.gateRejection(for: method, started: true)
            if androidOnlyNames.contains(method.rawValue) {
                // The platform gate wins regardless of start state.
                XCTAssertEqual(gatedBeforeStart?.code, "UNIMPLEMENTED", method.rawValue)
                XCTAssertEqual(gatedAfterStart?.code, "UNIMPLEMENTED", method.rawValue)
            } else {
                XCTAssertNotEqual(gatedBeforeStart?.code, "UNIMPLEMENTED", method.rawValue)
                XCTAssertNil(gatedAfterStart, method.rawValue)
            }
        }
    }

    func testNotStartedGateRejectsEveryIOSAdjustMethodAndHandleEventBeforeStart() {
        let available = TappAdjustMapping.Method.allCases.filter { !androidOnlyNames.contains($0.rawValue) }
        XCTAssertEqual(Set(available.map(\.rawValue)), iOSAdjustNames)
        for method in available {
            XCTAssertEqual(
                TappAdjustMapping.gateRejection(for: method, started: false),
                TappAdjustMapping.Rejection(code: "NOT_STARTED", message: TappAdjustMapping.notStartedMessage),
                method.rawValue
            )
            XCTAssertNil(TappAdjustMapping.gateRejection(for: method, started: true), method.rawValue)
        }
    }

