    func testCustomEventAndInvalidActions() {
        XCTAssertEqual(TappAdjustMapping.eventName(action: 0, customValue: "my_event"), "my_event")
        XCTAssertEqual(TappAdjustMapping.eventName(action: 0, customValue: nil), "custom_event_autogenerated")
        XCTAssertEqual(TappAdjustMapping.eventName(action: 0, customValue: ""), "custom_event_autogenerated")
        XCTAssertEqual(TappAdjustMapping.eventName(action: 0, customValue: "   "), "custom_event_autogenerated")
        XCTAssertEqual(TappAdjustMapping.eventName(action: 0, customValue: " my_event "), " my_event ")
        XCTAssertEqual(TappAdjustMapping.eventName(action: 1.0, customValue: "ignored"), "tapp_add_payment_info")
        let invalid: [Any] = [-1, 41, 1.5, Double.nan, Double.infinity, -Double.infinity,
                              true, false, NSNumber(value: true), "1", NSNull(), [1]]
        for value in invalid {
            XCTAssertNil(TappAdjustMapping.eventName(action: value, customValue: nil), "Unexpected valid action: \(value)")
        }
        XCTAssertNil(TappAdjustMapping.eventName(action: nil, customValue: nil))
    }

    func testMetadataPreservesBooleanAndNumericTypesAndDropsUnsupportedValues() throws {
        let input: [String: Any] = [
            "text": "hello", "yes": true, "no": NSNumber(value: false),
            "zero": NSNumber(value: 0), "one": NSNumber(value: 1), "fraction": 1.25,
            "negative": -4, "nan": Double.nan, "positiveInfinity": Double.infinity,
            "negativeInfinity": -Double.infinity, "null": NSNull(), "array": [1, 2],
            "object": ["nested": "value"], "date": Date(timeIntervalSince1970: 0)
        ]
        let result = try XCTUnwrap(TappAdjustMapping.metadata(input))
        XCTAssertEqual(Set(result.keys), Set(["text", "yes", "no", "zero", "one", "fraction", "negative"]))
        XCTAssertEqual(result["text"] as? String, "hello")
        XCTAssertTrue(result["yes"] is Bool)
        XCTAssertTrue(result["no"] is Bool)
        XCTAssertEqual(result["yes"] as? Bool, true)
        XCTAssertEqual(result["no"] as? Bool, false)
        XCTAssertTrue(result["one"] is Double)
        XCTAssertEqual(result["zero"] as? Double, 0)
        XCTAssertEqual(result["one"] as? Double, 1)
        XCTAssertEqual(result["fraction"] as? Double, 1.25)
        XCTAssertEqual(result["negative"] as? Double, -4)
        XCTAssertNil(TappAdjustMapping.metadata(nil))
        XCTAssertEqual(TappAdjustMapping.metadata([:])?.count, 0)
    }

